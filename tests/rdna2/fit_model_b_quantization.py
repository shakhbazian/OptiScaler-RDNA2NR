"""Fit independent B activation ranges; never borrow model A calibration constants."""
import argparse,csv,json,hashlib
from pathlib import Path
import numpy as np
C32=[0,1,2,28,29,30]
def main():
 p=argparse.ArgumentParser();p.add_argument('csv',type=Path);p.add_argument('output',type=Path);p.add_argument('--margin',type=float,default=1.15);a=p.parse_args()
 if not 1<=a.margin<=4:raise ValueError('Margin must be between 1 and 4')
 groups={}
 for row in csv.DictReader(a.csv.open()):
  groups.setdefault((int(row['block']),row['role']),[]).append(row)
 def values(block,role):
  rows=sorted(groups[block,role],key=lambda r:int(r['channel']))
  assert [int(r['channel']) for r in rows]==list(range(len(rows)))
  x=np.array([float(r['q9999']) for r in rows],dtype=np.float32)
  if not np.isfinite(x).all() or np.any(x<=0):raise ValueError('Invalid calibration range')
  return x
 inverse=[];fixed=[]
 for block in C32:
  x=np.concatenate([values(block,'ffn_expand_input'),values(block,'ffn_contract_input')])
  inv=np.exp2(np.clip(np.rint(-np.log2(np.maximum(x,2**-16))),-16,16)).astype(np.float32)
  ranges=x*inv*a.margin
  inverse.append(inv);fixed.append(np.r_[max(ranges[:32]),ranges[32:].reshape(4,32).max(1)]/127)
 entries=[];scales=[]
 for block in range(3,28):
  family=1 if block in list(range(3,9))+list(range(22,28)) else 2 if block in [9,10,20,21] else 3 if 11<=block<=18 else 4
  roles={2:'qkv_input',3:'attention_projection_input'} if family!=4 else {}
  if family==1:roles.update({12:'ffn_expand_input',13:'ffn_output_input'})
  elif family==2:roles.update({8:'ffn_expand_input',9:'ffn_output_input',10:'split_expand_input'})
  elif family==3:roles.update({0:'ffn_expand_input',1:'ffn_contract_input'})
  elif family==4:roles[6]='bridge_projection_input'
  if block==22:roles[7]='upsample_projection_input'
  for role,name in sorted(roles.items()):
   x=values(block,name)
   if role==10: x=x.reshape(-1,64).max(0) # resident split: eight batches share one input scale
   k=len(x);assert k%64==0
   v=np.maximum(x.reshape(-1,64).max(1)*a.margin,2**-24)/127
   entries.append((block,role,k,1320+len(scales)));scales.extend(v)
 def array(name,x):
  x=np.array(x,dtype=np.float32)
  def f(v):return f'{float(v):.9e}f'
  dims=''.join(f'[{n}]' for n in x.shape)
  body=','.join(f(v) for v in x) if x.ndim==1 else ',\n'.join('{'+','.join(f(v) for v in row)+'}' for row in x)
  return f'__device__ __constant__ float {name}{dims}={{\n{body}\n}};\n'
 text='#pragma once\n// Generated by tests/rdna2/fit_model_b_quantization.py. B 310.9.16.0 only.\n'
 text+='// 32 calibration scenes, Standard + strong controls; per-channel q99.99, margin '+str(a.margin)+'.\n'
 text+='// Source statistics SHA256: '+hashlib.sha256(a.csv.read_bytes()).hexdigest()+'\n'
 text+=array('nr_b_inverse',inverse)+array('nr_b_c32_scale',fixed)+array('nr_b_c32_inverse',1/np.array(fixed,dtype=np.float32))
 text+=array('nr_b_large_scale',scales)+array('nr_b_large_inverse',1/np.array(scales,dtype=np.float32))
 text+='inline int nr_b_range_offset(unsigned block,unsigned role,unsigned k,unsigned group){\n if(group!=64)return -1;\n switch(block*16+role){\n'
 for b,r,k,o in entries:text+=f' case {b*16+r}: return k=={k}?{o}:-1;\n'
 text+=' default:return -1;\n }\n}\n'
 a.output.write_text(text)
 print(json.dumps({'entries':len(entries),'large_scales':len(scales),'c32_blocks':C32,'margin':a.margin,'sha256':hashlib.sha256(text.encode()).hexdigest()}))
if __name__=='__main__':main()
