"""Generate typed production hook declarations from the installed D3D12 SDK."""
import argparse
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--sdk-header', type=Path, default=Path(r"C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0\um\d3d12.h"))
parser.add_argument('--check', action='store_true', help='Verify generated files without writing them')
options = parser.parse_args()
sdk = options.sdk_header
def write_generated(path, text):
    if options.check:
        if path.read_text(encoding='utf-8') != text:
            raise RuntimeError(f'Generated file differs: {path}')
    else:
        path.write_text(text, encoding='utf-8')
text = sdk.read_text()
methods = []
for version in range(11):
    interface = "ID3D12GraphicsCommandList" + (str(version) if version else "")
    body = text.split(interface + " : public ", 1)[1].split("\n    };", 1)[0]
    for ret, name, args in re.findall(r"virtual (\w+) STDMETHODCALLTYPE (\w+)\((.*?)\) = 0;", body, re.S):
        args = re.sub(r"_\w+_(?=\s|\()", "@SAL@", args)
        while "@SAL@" in args:
            start = args.index("@SAL@"); end = start + 5
            if end < len(args) and args[end] == "(":
                depth = 1; end += 1
                while depth:
                    depth += (args[end] == "(") - (args[end] == ")"); end += 1
            args = args[:start] + args[end:]
        args = " ".join(args.split())
        params = [] if args == "void" else args.split(",")
        names = [re.search(r"(\w+)\s*(?:\[.*?\])?$", p).group(1) for p in params]
        methods.append((ret, name, interface, params, names, version))
assert len(methods) == 77
root = Path(__file__).resolve().parents[1]
target = root / "OptiScaler/dlssnr/native/NativeMethods.h"
out = ["#pragma once", "// Generated by generate_native_hook_methods.py; do not edit.",
       '#include "NativeHookHub.h"', "#include <d3d12.h>", "namespace DlssNr::NativeHooks {"]
for slot, (ret,name,interface,params,names,version) in enumerate(methods,9):
    decl = ", ".join([interface+"* self"]+params)
    out += [f"using Fn_{name}={ret}(STDMETHODCALLTYPE*)({decl});",
            f"using M_{name}=Method<{slot},Fn_{name}>;"]
out += ["} // namespace DlssNr::NativeHooks"]
write_generated(target,"\n".join(out)+"\n")

manual = set('WriteBufferImmediate SetPipelineState RSSetDepthBias IASetIndexBufferStripCutValue Close Reset ClearState SetComputeRootSignature SetGraphicsRootSignature SetDescriptorHeaps ResourceBarrier OMSetRenderTargets BeginQuery EndQuery SetPredication BeginEvent EndEvent ExecuteBundle ExecuteIndirect'.split())
state = set('IASetPrimitiveTopology RSSetViewports RSSetScissorRects OMSetBlendFactor OMSetStencilRef SetPipelineState IASetIndexBuffer OMSetDepthBounds SetViewInstanceMask'.split())
recording = ['// Generated by generate_native_hook_methods.py; do not edit.']
for slot,(ret,name,interface,params,names,version) in enumerate(methods,9):
    if name in manual: continue
    body=[]; callnames=list(names)
    if name.startswith(('SetComputeRoot','SetGraphicsRoot')):
        graphics='true' if 'Graphics' in name else 'false'
        if name.endswith('32BitConstants'):
            body += ['if(RootParameterIndex>=64||DestOffsetIn32BitValues>64||Num32BitValuesToSet>64-DestOffsetIn32BitValues)throw std::runtime_error("root constant extent");',
                     'auto copy=Copy(static_cast<const UINT*>(pSrcData),Num32BitValuesToSet,64);',
                     'for(UINT i=0;i<Num32BitValuesToSet;++i){const auto value=copy[i],offset=DestOffsetIn32BitValues+i;',
                     f'Root({graphics},RootParameterIndex,2,[=](auto* p){{p->{name[:-1]}(RootParameterIndex,value,offset);}},offset);}}']
        else:
            kind=2 if name.endswith('32BitConstant') else 1 if name.endswith('DescriptorTable') else 3
            offset=',DestOffsetIn32BitValues' if kind==2 else ''
            body += [f'Root({graphics},RootParameterIndex,{kind},[=](auto* p){{p->{name}({", ".join(names)});}}{offset});']
    elif name in ('IASetVertexBuffers','SOSetTargets'):
        maxcount=32 if name.startswith('IA') else 4
        body += [f'if(StartSlot>{maxcount}||NumViews>{maxcount}-StartSlot)throw std::runtime_error("binding extent");',
                 'for(UINT i=0;i<NumViews;++i){const UINT index=StartSlot+i;const auto view=pViews?pViews[i]:'+('D3D12_VERTEX_BUFFER_VIEW' if maxcount==32 else 'D3D12_STREAM_OUTPUT_BUFFER_VIEW')+'{};',
                 f'State({slot},index,[=](auto* p){{p->{name}(index,1,&view);}});}}']
    elif version and name not in ('OMSetDepthBounds','SetViewInstanceMask','ResolveSubresourceRegion'):
        body += [f'(void){n};' for n in names]
        body += [f'Reject("{name} requires qualification");']
    else:
        if name=='CopyTextureRegion':
            body += ['auto dst=*pDst,src=*pSrc;Keep(dst.pResource);Keep(src.pResource);',
                     'const bool hasBox=pSrcBox!=nullptr;const auto box=hasBox?*pSrcBox:D3D12_BOX{};']
            callnames=['&dst','DstX','DstY','DstZ','&src','hasBox?&box:nullptr']
        elif name=='CopyTiles':
            body += ['Keep(pTiledResource);Keep(pBuffer);auto coordinate=*pTileRegionStartCoordinate;auto region=*pTileRegionSize;']
            callnames=['pTiledResource','&coordinate','&region','pBuffer','BufferStartOffsetInBytes','Flags']
        elif name=='DiscardResource':
            body += ['Keep(pResource);const bool hasRegion=pRegion!=nullptr;auto region=hasRegion?*pRegion:D3D12_DISCARD_REGION{};',
                     'auto rects=Copy(region.pRects,region.NumRects);']
            callnames=['pResource','hasRegion?&region:nullptr']
        else:
            for j,param in enumerate(params):
                n=names[j]
                if re.search(r'ID3D12\w+\s*\*',param):body += [f'Keep({n});']
                if n in ('pViewports','pRects','pSrcRect','pView','BlendFactor','ColorRGBA','Values','pData'):
                    ctype,count,limit={
                        'pViewports':('D3D12_VIEWPORT','NumViewports','16'),
                        'pRects':('D3D12_RECT','NumRects','65536' if name not in state else '16'),
                        'pSrcRect':('D3D12_RECT','pSrcRect?1:0','1'),
                        'pView':('D3D12_INDEX_BUFFER_VIEW','pView?1:0','1'),
                        'BlendFactor':('FLOAT','4','4'),'ColorRGBA':('FLOAT','4','4'),
                        'Values':('UINT' if name.endswith('Uint') else 'FLOAT','4','4'),
                        'pData':('unsigned char','Size','65536')}[n]
                    body += [f'auto copy{j}=Copy(static_cast<const {ctype}*>({n}),{count},{limit});']
                    callnames[j]=f'copy{j}.empty()?nullptr:copy{j}.data()'
                if n in ('RenderTargetView','DepthStencilView','ViewCPUHandle'):
                    heap={'RenderTargetView':'RTV','DepthStencilView':'DSV','ViewCPUHandle':'CBV_SRV_UAV'}[n]
                    body += [f'const auto handle{j}=Descriptor({n},D3D12_DESCRIPTOR_HEAP_TYPE_{heap});']
                    callnames[j]=f'handle{j}'
        invocation=f'p->{name}({", ".join(callnames)});'
        if name=='DiscardResource':invocation='auto local=region;local.pRects=rects.data();p->DiscardResource(pResource,hasRegion?&local:nullptr);'
        if version:invocation=f'Extended<{interface}>(p,[&](auto* x){{x->{name}({", ".join(callnames)});}});'
        operation=f'State({slot},0,' if name in state else 'Command('
        body += [operation+'[=](auto* p)'+(' mutable' if name=='ResolveSubresourceRegion' else '')+'{'+invocation+'});']
    recording += [f'    void {name}({", ".join(params)}) {{',*['        '+line for line in body],'    }']
write_generated(target.parent/'NativeRecordingMethods.inl','\n'.join(recording)+'\n')

observe=['// Generated by generate_native_hook_methods.py; do not edit.']
for slot,(ret,name,interface,params,names,version) in enumerate(methods,9):
    decl=', '.join([interface+'* self']+params+(['HRESULT result'] if ret=='HRESULT' else []))
    observe += [f'void Observe_{name}({decl}) noexcept {{']
    if name=='Reset':observe += ['    OnReset(self,pInitialState,SUCCEEDED(result));(void)pAllocator;']
    elif name=='Close':observe += ['    OnClose(self,SUCCEEDED(result));']
    else:observe += [f'    Record(self,[&](Recording& r){{r.{name}({", ".join(names)});}});']
    observe += ['}']
observe += ['void InstallObservers(){']
for _,name,*_ in methods:observe += [f'    NativeHooks::M_{name}::observer.store(Observe_{name},std::memory_order_release);']
observe += ['}', 'bool SurveyList(ID3D12GraphicsCommandList* list,std::vector<void*>& aliases,bool install){','    bool ok=true;']
for version in range(11):
    interface='ID3D12GraphicsCommandList'+(str(version) if version else '')
    observe += ['    {',f'    ComPtr<{interface}> ptr;',
                '    if(SUCCEEDED(list->QueryInterface(IID_PPV_ARGS(&ptr)))){',
                '        aliases.push_back(ptr.Get());auto** table=*reinterpret_cast<void***>(ptr.Get());']
    for slot,(_,name,_,_,_,v) in enumerate(methods,9):
        if v>version:continue
        observe += [f'        ok=(install?NativeHooks::M_{name}::Ensure(table[{slot}])==NO_ERROR:NativeHooks::M_{name}::Covered(table[{slot}]))&&ok;']
    observe += ['    }}']
observe += ['    return ok;', '}', 'bool KnownListInterface(REFIID iid) noexcept {',
            '    return iid==__uuidof(IUnknown)||iid==__uuidof(ID3D12Object)||iid==__uuidof(ID3D12DeviceChild)||iid==__uuidof(ID3D12CommandList)']
for version in range(11):observe += ['        ||iid==__uuidof(ID3D12GraphicsCommandList'+(str(version) if version else '')+')']
observe += ['        ;','}']
write_generated(target.parent/'NativeRecorderMethods.inl','\n'.join(observe)+'\n')
print(f"{'Verified' if options.check else 'Generated'} {len(methods)} typed production command-list methods")
